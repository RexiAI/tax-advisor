const STOPWORD_SET = new Set(SPANISH_STOPWORDS);

/** NFD decomposition, combining marks removed, lowercased. */
export function normalizeText(text: string): string {
  return text
    .normalize('NFD')
    .replace(/[\u0300-\u036f]/g, '')
    .toLowerCase();
}

/** Splits on non-alphanumerics and drops empty tokens and stopwords. */
export function normalizeTerms(text: string): string[] {
  return normalizeText(text)
    .split(/[^a-z0-9]+/)
    .filter((term) => term !== '' && !STOPWORD_SET.has(term));
}
